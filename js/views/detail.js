// 상세 패널 (PRD §5 기능 2-4): 업무 정보, 출처·원문, 연결된 실시사항, 메모, 확인 요청·답변
import {
  state, handlers, render, act, today, esc, findTask, memberFull, memberName, docOf, evidenceOf, logsOf,
  requestsOf, statusChip, typeTag, statusSelect, options, addNote, completeTask, uncompleteTask,
  deleteTask, unlinkLog, answerRequest, closeRequest, describeResult, toast, outOfLogPeriod, needName,
} from '../core.js';
import { fmtK, fmtTime } from '../dates.js';
import { CYCLE_LABEL, STATUS_LABEL, METHOD_LABEL, TYPE_LABEL, ddayLabel, orderElapsed, isOverdue } from '../rules.js';
import { DOC_TYPES } from '../extract.js';

const REL = { plan: '계획', log: '실시', order: '지시' };
const REQ_STATE = { pending: '답변 대기', answered: '답변 완료', closed: '처리 완료' };

export function renderDetail() {
  if (!state.detailId) return '';
  const t = findTask(state.detailId);
  if (!t) { state.detailId = null; return ''; }
  const T = today();
  const row = (k, v) => (v ? `<div class="kv"><dt>${k}</dt><dd>${v}</dd></div>` : '');
  const prev = t.prevTaskId ? findTask(t.prevTaskId) : null;
  const ev = evidenceOf(t.id);
  const logs = logsOf(t.id);
  const reqs = requestsOf(t.id);
  const notes = [...(t.notes || [])].reverse();

  return `
  <div class="drawer-back" data-act="closeDetail"></div>
  <aside class="drawer" role="dialog" aria-label="업무 상세">
    <div class="drawer-head">
      <div>${typeTag(t)} ${t.autoGenerated ? '<span class="tag">자동 생성</span>' : ''}</div>
      <button class="btn icon" data-act="closeDetail" aria-label="닫기">✕</button>
    </div>
    <h2 class="drawer-title">${esc(t.title)}</h2>
    <div class="drawer-status">
      ${statusChip(t, T)}
      ${isOverdue(t, T) && outOfLogPeriod(t) ? '<span class="chip gray">실시자료 기간 밖</span>' : ''}
      <span class="grow"></span>
      ${statusSelect(t)}
      ${t.status === 'done'
        ? `<button class="btn small" data-act="detailUndo" data-id="${t.id}">완료 취소</button>`
        : `<button class="btn small ok" data-act="detailDone" data-id="${t.id}">✓ 완료 처리</button>`}
    </div>

    <section class="sec">
      <dl class="kvs">
        ${row('구분', TYPE_LABEL[t.type] + (t.type === 'cycle' ? ` · ${CYCLE_LABEL[t.cycle] || ''}` : ''))}
        ${row('담당자', esc(memberFull(t.assigneeId)) || '<span class="muted">미정</span>')}
        ${row('시작일', fmtK(t.startDate))}
        ${row('마감일', t.dueDate ? `${fmtK(t.dueDate)} ${t.status !== 'done' ? `<b class="dd">${ddayLabel(t.dueDate, T)}</b>` : ''}` : '<span class="muted">없음 (일정 미정)</span>')}
        ${t.type === 'order' ? row('지시일자', `${fmtK(t.orderDate)} <b class="dd">지시 후 D+${orderElapsed(t, T) ?? '?'}</b>`) : ''}
        ${t.type === 'order' ? row('지시자', esc(t.orderedBy || '')) : ''}
        ${t.status === 'done' ? row('완료', `${fmtK(t.completedAt)} · ${METHOD_LABEL[t.completedMethod] || ''}${t.completedBy ? ` · ${esc(memberName(t.completedBy))}` : ''}`) : ''}
        ${prev ? row('이전 회차', `<a href="#" data-act="openDetail" data-id="${prev.id}">${fmtK(prev.dueDate)} 마감분</a>`) : ''}
      </dl>
    </section>

    ${t.pendingChange && t.status !== 'done' ? `
    <section class="sec chg-sec">
      <h4>기한 변경 반영 대기</h4>
      <div class="chg-dates"><s>${fmtK(t.pendingChange.fromDue) || '없음'}</s> → <b>${fmtK(t.pendingChange.dueDate)}</b></div>
      ${t.pendingChange.sources.map((s) => `<div class="src"><div class="src-head"><b>${esc(docOf(s.documentId)?.fileName || '문서')}</b> <span class="muted">${esc(s.location || '')}</span></div><blockquote>${esc(s.text)}</blockquote></div>`).join('')}
      <div class="chg-actions"><button class="btn teal" data-act="applyChange" data-id="${t.id}">변경 반영</button><button class="btn outline" data-act="holdChange" data-id="${t.id}">보류</button></div>
    </section>` : ''}

    <section class="sec">
      <h4>출처</h4>
      ${ev.length ? ev.map((e) => {
        const d = docOf(e.documentId);
        return `<div class="src"><div class="src-head"><b>${esc(d?.fileName || '(삭제된 문서)')}</b> <span class="muted">${esc(DOC_TYPES[d?.docType] || '')} · ${esc(e.location || '')} · ${REL[e.relation] || ''}</span></div><blockquote>${esc(e.text)}</blockquote></div>`;
      }).join('') : '<div class="muted">직접 등록한 업무입니다.</div>'}
    </section>

    <section class="sec">
      <h4>연결된 실시사항</h4>
      ${logs.length ? logs.map((l) => `
        <div class="src"><div class="src-head"><b>${fmtK(l.date)}</b> ${esc(memberName(l.assigneeId))} <span class="grow"></span><button class="btn small" data-act="detailUnlink" data-id="${l.id}">연결 해제</button></div>
        <blockquote>${esc(l.raw || l.content)}</blockquote></div>`).join('') : '<div class="muted">연결된 실시사항이 없습니다.</div>'}
    </section>

    <section class="sec">
      <h4>메모·진행 내용</h4>
      <form class="inline-form" data-submit="detailNote" data-id="${t.id}">
        <input name="text" placeholder="진행 내용을 적고 Enter" autocomplete="off" required>
        <button class="btn small">추가</button>
      </form>
      ${notes.length ? notes.map((n) => `<div class="note"><span class="muted">${fmtK(n.date)} ${esc(memberName(n.authorId) || '이름 미선택')}</span> ${n.kind === 'progress' ? '<span class="badge blue">진행 내용</span> ' : ''}${esc(n.text)}</div>`).join('') : '<div class="muted">메모가 없습니다.</div>'}
    </section>

    <section class="sec">
      <div class="sec-head"><h4>진행 확인 요청</h4><button class="btn small" data-act="requestModal" data-id="${t.id}">확인 요청 보내기</button></div>
      ${reqs.length ? reqs.map((r) => `
        <div class="req-card ${r.state}">
          <div class="muted">${esc(memberName(r.requesterId))} → ${esc(memberName(r.targetId))} · ${fmtTime(r.requestedAt)} · <b>${REQ_STATE[r.state]}</b></div>
          <div class="req-q">💬 ${esc(r.content)}</div>
          ${r.answer ? `<div class="req-a">↳ ${esc(r.answer)} <span class="muted">(${esc(memberName(r.answeredBy) || '')} ${fmtTime(r.answeredAt)})</span></div>` : ''}
          ${r.state === 'pending' ? `
            <form class="answer-form" data-submit="detailAnswer" data-rid="${r.id}">
              <textarea name="answer" rows="2" placeholder="답변 (예: 11.4까지 제출 예정)" required></textarea>
              <div class="row-inline"><button class="btn small primary">답변 등록</button></div>
            </form>` : ''}
          ${r.state === 'answered' ? `<button class="btn small" data-act="closeReq" data-rid="${r.id}">처리 완료로 닫기</button>` : ''}
        </div>`).join('') : '<div class="muted">확인 요청이 없습니다.</div>'}
    </section>

    <div class="drawer-foot">
      <button class="btn" data-act="editTask" data-id="${t.id}">수정</button>
      <button class="btn danger" data-act="deleteTask" data-id="${t.id}">삭제</button>
    </div>
  </aside>`;
}

Object.assign(handlers, {
  closeDetail() { state.detailId = null; render(); },
  detailDone: act(async (el) => {
    const res = await completeTask(findTask(el.dataset.id));
    toast(['완료 처리했습니다.', describeResult(res)].join(' '), 'ok');
  }),
  detailUndo: act(async (el) => {
    const t = findTask(el.dataset.id);
    if (!confirm(`'${t.title}' 완료를 취소할까요? 완료 전 상태(${STATUS_LABEL[t.prevStatus] || '미착수'})로 돌아갑니다.`)) return;
    const res = await uncompleteTask(t);
    toast(['완료를 취소했습니다.', describeResult(res)].join(' '));
  }),
  detailUnlink: act(async (el) => {
    const log = state.db.daily_logs.find((l) => l.id === el.dataset.id);
    if (!log || !confirm('이 실시사항과 업무의 연결을 풀까요? 실시사항으로 완료된 업무는 완료 전 상태로 돌아갑니다.')) return;
    const res = await unlinkLog(log);
    toast(['연결을 풀었습니다.', describeResult(res)].join(' '));
  }),
  detailNote: act(async (form) => {
    const text = form.text.value.trim();
    if (!text) return;
    await addNote(findTask(form.dataset.id), text);
    toast('메모를 추가했습니다.', 'ok');
  }),
  detailAnswer: act(async (form) => {
    if (needName()) return;
    const req = state.db.check_requests.find((r) => r.id === form.dataset.rid);
    await answerRequest(req, form.answer.value.trim());
    toast('답변을 등록했습니다.', 'ok');
  }),
  closeReq: act(async (el) => {
    await closeRequest(state.db.check_requests.find((r) => r.id === el.dataset.rid));
    toast('확인 요청을 처리 완료로 닫았습니다.', 'ok');
  }),
  deleteTask: act(async (el) => {
    const t = findTask(el.dataset.id);
    if (!t || !confirm(`'${t.title}' 업무를 삭제할까요?\n출처 기록과 확인 요청도 함께 지워지고, 연결된 실시사항은 연결만 풀립니다.`)) return;
    await deleteTask(t);
    if (state.detailId === t.id) state.detailId = null;
    toast('삭제했습니다.');
  }),
});
