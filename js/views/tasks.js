// 화면 ② 업무 관리: 진행 중 업무 / 완료 이력 (PRD §6 화면 ②)
import {
  state, handlers, render, act, today, esc, options, memberOptions, memberName, findTask, statusChip,
  typeTag, dueText, evidenceOf, uncompleteTask, describeResult, toast,
} from '../core.js';
import { fmtK } from '../dates.js';
import { TYPE_LABEL, STATUS_LABEL, METHOD_LABEL, byDue, displayStatus } from '../rules.js';

export function renderTasks() {
  const g = state.mgmt;
  const T = today();
  const tab = (v, l) => `<button class="tab-btn ${g.view === v ? 'on' : ''}" data-act="mgmtView" data-v="${v}">${l}</button>`;
  const filters = `
    <label>구분<select data-chg="mgmtFilter" data-f="type">${options(TYPE_LABEL, g.type, { empty: '전체' })}</select></label>
    <label>담당자<select data-chg="mgmtFilter" data-f="assignee">${memberOptions(g.assignee, '전체')}<option value="-" ${g.assignee === '-' ? 'selected' : ''}>담당 미정</option></select></label>`;
  const byAssignee = (t) => !g.assignee || (g.assignee === '-' ? !t.assigneeId : t.assigneeId === g.assignee);
  let body;
  if (g.view === 'open') {
    const list = state.db.tasks.filter((t) => t.status !== 'done' && (!g.type || t.type === g.type) && byAssignee(t)
      && (!g.status || (g.status === 'overdue' ? t.dueDate && t.dueDate < T : displayStatus(t, T) === g.status))).sort(byDue);
    body = `
      <div class="filters">${filters}
        <label>상태<select data-chg="mgmtFilter" data-f="status">${options({ planned: '예정', notstarted: '미착수', doing: '진행중', overdue: '⚠ 완료 미확인' }, g.status, { empty: '전체' })}</select></label>
        <span class="grow"></span><span class="muted">${list.length}건</span>
        <button class="btn primary" data-act="newTask">+ 업무 추가</button>
      </div>
      <div class="table-wrap"><table class="tbl">
        <thead><tr><th>업무명</th><th>구분</th><th>담당자</th><th>시작일</th><th>마감일</th><th>상태</th><th>출처</th><th></th></tr></thead>
        <tbody>${list.map((t) => `
          <tr>
            <td><a href="#" data-act="openDetail" data-id="${t.id}">${esc(t.title)}</a>${t.autoGenerated ? ' <span class="tag">자동 생성</span>' : ''}</td>
            <td>${typeTag(t)}</td>
            <td>${esc(memberName(t.assigneeId)) || '<span class="muted">미정</span>'}</td>
            <td>${fmtK(t.startDate)}</td>
            <td class="nowrap">${dueText(t, T)}</td>
            <td>${statusChip(t, T)}</td>
            <td>${evidenceOf(t.id).length ? `<span title="문서에서 가져옴">📄 ${evidenceOf(t.id).length}</span>` : '<span class="muted" title="직접 등록">✍</span>'}</td>
            <td class="nowrap"><button class="btn small" data-act="editTask" data-id="${t.id}">수정</button> <button class="btn small danger" data-act="deleteTask" data-id="${t.id}">삭제</button></td>
          </tr>`).join('') || '<tr><td colspan="8" class="empty">조건에 맞는 업무가 없습니다.</td></tr>'}
        </tbody></table></div>`;
  } else {
    const list = state.db.tasks.filter((t) => t.status === 'done' && (!g.type || t.type === g.type) && byAssignee(t)
      && (!g.from || (t.completedAt || '') >= g.from) && (!g.to || (t.completedAt || '') <= g.to))
      .sort((a, b) => (b.completedAt || '').localeCompare(a.completedAt || ''));
    body = `
      <div class="filters">${filters}
        <label>완료일<input type="date" data-chg="mgmtFilter" data-f="from" value="${esc(g.from)}"></label>
        <label>~<input type="date" data-chg="mgmtFilter" data-f="to" value="${esc(g.to)}"></label>
        <span class="grow"></span><span class="muted">${list.length}건</span>
      </div>
      <div class="table-wrap"><table class="tbl">
        <thead><tr><th>업무명</th><th>구분</th><th>담당자</th><th>마감일</th><th>완료일</th><th>완료 방법</th><th></th></tr></thead>
        <tbody>${list.map((t) => `
          <tr>
            <td><a href="#" data-act="openDetail" data-id="${t.id}">✓ ${esc(t.title)}</a></td>
            <td>${typeTag(t)}</td>
            <td>${esc(memberName(t.assigneeId))}</td>
            <td>${fmtK(t.dueDate)}</td>
            <td>${fmtK(t.completedAt)}</td>
            <td>${METHOD_LABEL[t.completedMethod] || ''}</td>
            <td><button class="btn small" data-act="historyUndo" data-id="${t.id}">완료 취소</button></td>
          </tr>`).join('') || '<tr><td colspan="7" class="empty">완료 이력이 없습니다.</td></tr>'}
        </tbody></table></div>`;
  }
  return `<div class="page"><div class="page-head"><div class="tabs-inline">${tab('open', '진행 중 업무')}${tab('history', '완료 이력')}</div></div>${body}</div>`;
}

Object.assign(handlers, {
  mgmtView(el) { state.mgmt.view = el.dataset.v; state.mgmt.status = ''; render(); },
  mgmtFilter(el) { state.mgmt[el.dataset.f] = el.value; render(); },
  historyUndo: act(async (el) => {
    const t = findTask(el.dataset.id);
    if (!t || !confirm(`'${t.title}' 완료를 취소할까요?\n상태가 완료 전(${STATUS_LABEL[t.prevStatus] || '미착수'})으로 돌아가고 완료일·완료 방법이 지워집니다.${t.completedMethod === 'log' ? '\n연결된 실시사항은 연결만 풀리고 기록은 남습니다.' : ''}`)) return;
    const res = await uncompleteTask(t);
    toast(['완료를 취소했습니다.', describeResult(res)].join(' '));
  }),
});
