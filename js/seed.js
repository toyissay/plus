// 교육·시연용 가상 샘플 데이터 (PRD §12). 실제 부대명·실명·실제 업무 내용이 아니다.
// 날짜는 기준일(T)을 기준으로 배치해 언제 초기화해도 모든 묶음과 색이 보이게 한다.
import { addDays, mondayOf } from './dates.js';
import { nextDates } from './rules.js';

export function buildSeed(T) {
  const ws = mondayOf(T);
  const d = (n) => addDays(T, n); // 기준일 기준
  const w = (n) => addDays(ws, n); // 이번 주 월요일 기준
  const y = T.slice(0, 4);
  const now = new Date().toISOString();
  const at = (date, hh = '09:00') => new Date(`${date}T${hh}:00+09:00`).toISOString();

  // 구성원은 사람이 아니라 직위·부서 단위다. 전체 검토자 2, 담당 부서 7.
  const members = [
    ['m1', '지휘관', 'reviewer'],
    ['m2', '계획 운용과장', 'reviewer'],
    ['u1', '운용과', 'member'],
    ['u2', '군수과', 'member'],
    ['u3', '인사과', 'member'],
    ['u4', '1중대', 'member'],
    ['u5', '2중대', 'member'],
    ['u6', '3중대', 'member'],
    ['u7', '본부중대', 'member'],
  ].map(([id, name, role], i) => ({ id, name, rank: '', position: '', role, order: i }));
  // 아래 샘플은 업무 성격별 키(m3~m12)로 적고, 담당 부서로 옮긴다.
  const OWNER = { m3: 'u1', m4: 'u1', m12: 'u1', m5: 'u2', m11: 'u2', m10: 'u3', m6: 'u4', m8: 'u5', m9: 'u6', m7: 'u7' };
  const P = (id) => OWNER[id] || id;

  const documents = [
    { id: 'doc-annual', fileName: `${y}년 연간 부대운영계획 (초기 샘플)`, docType: 'annual', writtenDate: `${y}-01-05`, periodFrom: `${y}-01-01`, periodTo: `${y}-12-31` },
    { id: 'doc-weekly', fileName: '주간 부대운영계획 (초기 샘플)', docType: 'weekly', writtenDate: w(-3), periodFrom: w(0), periodTo: w(6) },
    { id: 'doc-logs', fileName: '2주 전 실시사항 (초기 샘플)', docType: 'logs', writtenDate: w(-7), periodFrom: w(-14), periodTo: w(-8) },
    { id: 'doc-minutes', fileName: '주간 업무 회의록 (초기 샘플)', docType: 'minutes', writtenDate: d(-12), periodFrom: d(-12), periodTo: d(-12) },
  ].map((x) => ({ ...x, hash: null, seed: true, importedAt: now, importedBy: 'm2', extractedText: '(초기 샘플 데이터: 원본 파일 없음)' }));

  const base = {
    notes: [], status: 'todo', startDate: null, dueDate: null, cycle: null, orderDate: null, orderedBy: null,
    assigneeId: null, completedAt: null, completedMethod: null, completedBy: null, prevStatus: null,
    prevTaskId: null, autoGenerated: false,
  };
  const tasks = [];
  const T_ = (id, o) => { const t = { ...base, id, ...o }; tasks.push(t); return t; };
  const cyc = (id, cycle, title, assigneeId, dueDate, o = {}) => T_(id, { type: 'cycle', cycle, title, assigneeId, dueDate, ...o });
  const done = (date, method = 'manual', prevStatus = 'doing') => ({ status: 'done', completedAt: date, completedMethod: method, prevStatus });

  // 주기 업무 (19건 + 자동 생성 회차)
  const c1 = cyc('c1', 'monthly', '월간 예산 집행 실적 보고', 'm3', d(2), done(d(-1), 'log'));
  cyc('c2', 'monthly', '월간 안전점검 결과 보고', 'm3', d(-4), { startDate: d(-10) });
  cyc('c3', 'weekly', '주간 업무 실적 보고', 'm7', w(4), { startDate: w(0) });
  cyc('c4', 'monthly', '월간 교육훈련 결과 보고', 'm4', d(14));
  cyc('c5', 'quarterly', '분기 부대운영 성과 분석', 'm2', d(26), { startDate: d(10) });
  cyc('c6', 'annual', '연간 교육훈련 계획 수립', 'm4', d(45), { status: 'doing', notes: [{ date: d(-6), at: at(d(-6), '15:20'), authorId: 'm4', text: '부서별 소요 취합 완료, 초안 작성 착수' }] });
  cyc('c7', 'monthly', '월간 보안점검 실시', 'm12', d(0), { status: 'doing' });
  cyc('c8', 'monthly', '월간 보안점검 결과 보고', 'm12', d(3));
  cyc('c9', 'weekly', '주간 차량 운행 실적 정리', 'm11', w(-3));
  const c10 = cyc('c10', 'monthly', '월간 정보체계 점검', 'm8', w(-10), done(w(-11), 'log'));
  cyc('c11', 'quarterly', '분기 동원자원 현황 보고', 'm9', d(-6), { status: 'doing' });
  const c12 = cyc('c12', 'monthly', '월간 인사 현황 보고', 'm10', w(4), done(d(-1), 'log', 'todo'));
  cyc('c13', 'weekly', '주간 탄약·물자 재고 확인', 'm11', w(3), { startDate: w(0) });
  cyc('c14', 'monthly', '월간 교육훈련 실적 입력', 'm4', w(9));
  cyc('c15', 'weekly', '주간 회의 자료 작성', 'm2', w(7));
  cyc('c16', 'annual', '연간 부대운영계획 성과 평가', 'm1', d(58));
  cyc('c17', 'quarterly', '분기 예산 소요 판단', 'm5', d(70));
  cyc('c18', 'monthly', '월간 시설 안전점검', 'm6', d(10), {
    startDate: d(5),
    // 기한 변경 반영 대기 예시: 주간계획·회의록이 기존 마감보다 앞당긴 날짜를 제시
    pendingChange: {
      dueDate: d(7), fromDue: d(10), proposedAt: now,
      sources: [
        { documentId: 'doc-weekly', location: '표1 9행', text: `${d(7).slice(5).replace('-', '.')}. | 시설 안전점검 결과 제출 | 1중대` },
        { documentId: 'doc-minutes', location: '9번째 문단', text: `시설 안전점검 결과는 ${Number(d(7).slice(5, 7))}월 ${Number(d(7).slice(8))}일로 앞당겨 제출` },
      ],
    },
  });
  cyc('c19', 'monthly', '월간 장비 가동률 보고', 'm8', d(-15));
  for (const [src, id] of [[c1, 'c1n'], [c10, 'c10n'], [c12, 'c12n']]) {
    T_(id, { type: 'cycle', cycle: src.cycle, title: src.title, assigneeId: src.assigneeId, ...nextDates(src), prevTaskId: src.id, autoGenerated: true });
  }

  // 지휘관 지시사항 (7건)
  const ord = (id, title, orderedBy, assigneeId, orderDate, dueDate, o = {}) => T_(id, { type: 'order', title, orderedBy, assigneeId, orderDate, dueDate, ...o });
  ord('o1', '동계 안전대책 수립 보고', '사단장', 'm6', d(-12), d(12), { status: 'doing', notes: [{ date: d(-5), at: at(d(-5), '16:40'), authorId: 'm6', text: '초안 작성 중, 과장 검토 후 보고 예정' }] });
  ord('o2', '부대 정보보호 교육 강화', '사단장', 'm12', d(-40), null);
  ord('o3', '훈련장 환경 정비', '연대장', 'm11', d(-20), d(-1));
  ord('o4', '간부 업무 인수인계 체계 정비', '사단장', 'm10', d(-3), d(4));
  ord('o5', '장병 고충 처리 현황 점검', '연대장', 'm7', d(-25), null, done(w(-13), 'log', 'todo'));
  ord('o6', '지휘관 지시사항 관리 대장 정리', '계획 운용과장', 'm3', d(-8), null, { status: 'doing' });
  ord('o7', '차량 정비 실태 확인', '연대장', 'm11', d(-30), null, done(w(-11), 'log'));

  // 수시 업무 (4건, 일정 미정 2건)
  T_('a1', { type: 'adhoc', title: '신규 전입 간부 교육 자료 준비', assigneeId: 'm4', dueDate: d(1), status: 'doing' });
  T_('a2', { type: 'adhoc', title: '체육대회 계획 수립', assigneeId: 'm10' });
  T_('a3', { type: 'adhoc', title: '부대 홈페이지 공지 정비' });
  T_('a4', { type: 'adhoc', title: '보고서 양식 개선안 작성', assigneeId: 'm2', dueDate: w(6) });
  tasks.forEach((t) => { t.createdAt = now; t.updatedAt = now; });

  // 업무 근거 (출처 문서·위치·원문)
  const task_evidence = [];
  const ev = (taskId, documentId, location, text, relation) => task_evidence.push({ id: `ev-${task_evidence.length + 1}`, taskId, documentId, location, text, relation });
  const byId = Object.fromEntries(tasks.map((t) => [t.id, t]));
  const name = (id) => members.find((m) => m.id === P(id))?.name || '';
  const CL = { annual: '연간', quarterly: '분기', monthly: '월간', weekly: '주간' };
  ['c1', 'c2', 'c3', 'c4', 'c5', 'c6', 'c7', 'c8', 'c9', 'c10', 'c11', 'c12', 'c13', 'c14', 'c15', 'c16', 'c17', 'c18', 'c19'].forEach((id, i) => {
    const t = byId[id];
    ev(id, 'doc-annual', `표1 ${i + 2}행`, `${CL[t.cycle]} | ${t.title} | ${name(t.assigneeId)} | ${t.dueDate.slice(5).replace('-', '.')}.`, 'plan');
  });
  ['o1', 'o2', 'o4', 'o6'].forEach((id, i) => ev(id, 'doc-minutes', `${5 + i}번째 문단`, `${i + 1}. ${byId[id].title} (담당: ${name(byId[id].assigneeId)})`, 'order'));
  ev('c7', 'doc-weekly', '표1 3행', `${w(1).slice(5).replace('-', '.')}. | 월간 보안점검 | 운용과`, 'plan');
  ev('c13', 'doc-weekly', '표1 5행', `${w(3).slice(5).replace('-', '.')}. | 탄약·물자 재고 확인 | 군수과`, 'plan');

  // 주간 예정사항 (12건)
  const weekly_plans = [
    [w(0), 'm2', '주간 업무 회의'], [w(0), 'm4', '신규 전입 간부 교육 자료 준비'], [w(1), 'm12', '월간 보안점검'],
    [w(2), 'm3', '월간 예산 집행 실적 보고'], [w(2), 'm12', '정보보호 교육 계획 검토'], [w(3), 'm11', '탄약·물자 재고 확인'],
    [w(4), 'm7', '주간 업무 실적 보고'], [w(4), 'm10', '간부 업무 인수인계 체계 정비 보고'], [w(7), 'm2', '주간 회의 자료 작성'],
    [w(9), 'm4', '월간 교육훈련 실적 입력'], [w(10), 'm6', '시설 안전점검 사전 준비'], [w(11), 'm6', '동계 안전대책 중간 보고'],
  ].map(([plannedDate, assigneeId, content], i) => ({
    id: `wp-${i + 1}`, weekStart: mondayOf(plannedDate), plannedDate, assigneeId, content,
    documentId: plannedDate <= w(6) ? 'doc-weekly' : null,
  }));

  // 일일 실시사항 (18건: 2주 전 문서분 + 이번 주 직접 입력분)
  const daily_logs = [
    [w(-14), 'm10', '장병 고충 상담 2건 처리', '완료', null, 'doc-logs'],
    [w(-13), 'm7', '장병 고충 처리 현황 점검 완료', '완료', 'o5', 'doc-logs'],
    [w(-12), 'm6', '동계 안전대책 초안 작성 착수', '진행', 'o1', 'doc-logs'],
    [w(-12), 'm1', '지휘관 지시사항 이행 점검 회의 주관', '완료', null, 'doc-logs'],
    [w(-11), 'm8', '월간 정보체계 점검 완료', '완료', 'c10', 'doc-logs'],
    [w(-11), 'm11', '차량 정비 실태 확인 완료', '완료', 'o7', 'doc-logs'],
    [w(-10), 'm9', '분기 동원자원 현황 자료 취합 중', '진행', 'c11', 'doc-logs'],
    [w(-10), 'm5', '예산 집행 현황 자료 요청', '진행', null, 'doc-logs'],
    [w(-9), 'm4', '전입 간부 교육 일정 협의', '진행', null, 'doc-logs'],
    [w(-9), 'm12', '정보보호 교육 계획 검토 중', '진행', null, 'doc-logs'],
    [w(-8), 'm2', '주간 업무 회의 개최', '완료', null, 'doc-logs'],
    [d(-1), 'm3', '월간 예산 집행 실적 보고 제출 완료', '완료', 'c1', null],
    [d(-1), 'm10', '월간 인사 현황 보고 제출 완료', '완료', 'c12', null],
    [d(-1), 'm6', '동계 안전대책 관련 회의 참석', '진행', null, null],
    [d(0), 'm12', '월간 보안점검 1차 진행', '진행', 'c7', null],
    // 진행중 업무는 모두 진행 기록이 있도록 한다
    [d(-6), 'm4', '연간 교육훈련 부서별 소요 취합, 계획 초안 작성 착수', '진행', 'c6', null],
    [d(-4), 'm3', '지휘관 지시사항 관리 대장 정리 착수', '진행', 'o6', null],
    [d(-2), 'm4', '신규 전입 간부 교육 자료 초안 작성 중', '진행', 'a1', null],
  ].map(([date, assigneeId, content, result, taskId, documentId], i) => ({
    id: `dl-${i + 1}`, date, assigneeId, content, result, taskId, documentId,
    location: documentId ? `${i + 2}번째 문단` : '',
    raw: documentId ? `○ ${date.slice(5).replace('-', '.')}. ${name(assigneeId)}: ${content}` : '',
  }));
  daily_logs.filter((l) => l.taskId && l.documentId).forEach((l) => ev(l.taskId, l.documentId, l.location, l.raw, 'log'));

  // 진행 확인 요청 (대기 2건, 답변 완료 1건)
  const check_requests = [
    { id: 'cr-1', taskId: 'c2', requesterId: 'm1', targetId: 'm3', content: '월간 안전점검 결과 보고, 진행 상황 알려주세요.', requestedAt: at(d(-1), '17:10'), answer: null, answeredAt: null, answeredBy: null, state: 'pending' },
    { id: 'cr-2', taskId: 'c11', requesterId: 'm1', targetId: 'm9', content: '분기 동원자원 현황 보고 일정 확인 바랍니다.', requestedAt: at(d(-3), '10:00'), answer: '자료 취합 마무리 중이며 이번 주 목요일까지 보고 예정입니다.', answeredAt: at(d(-2), '14:30'), answeredBy: 'm9', state: 'answered' },
    { id: 'cr-3', taskId: 'c9', requesterId: 'm2', targetId: 'm11', content: '지난주 차량 운행 실적 정리 완료 여부 확인 부탁합니다.', requestedAt: at(d(0), '08:40'), answer: null, answeredAt: null, answeredBy: null, state: 'pending' },
  ];

  // 업무 성격별 키를 담당 부서 id로 바꾼다
  const remap = (list, fields) => list.forEach((r) => fields.forEach((f) => { if (r[f]) r[f] = P(r[f]); }));
  remap(tasks, ['assigneeId']);
  tasks.forEach((t) => remap(t.notes, ['authorId']));
  remap(weekly_plans, ['assigneeId']);
  remap(daily_logs, ['assigneeId']);
  remap(check_requests, ['requesterId', 'targetId', 'answeredBy']);
  return { members, documents, tasks, task_evidence, weekly_plans, daily_logs, check_requests };
}
